#!/bin/sh
# Expose the skills in .agents/skills/ to every AI tool the team uses.
#
#   sh scripts/sync-agent-skills.sh          regenerate the stubs
#   sh scripts/sync-agent-skills.sh --check  fail if the stubs are out of date (used in CI)
#
# .agents/skills/<name>/SKILL.md is the single source of truth (Agent Skills format).
#   - Codex and OpenCode read .agents/skills/ directly.
#   - Claude Code reads .claude/skills/, Cursor reads .cursor/skills/ — this script writes a small
#     stub there with the same name + description that points back to the real file.
# Stubs instead of symlinks, so it works on Windows checkouts too.
# Another tool that needs its own folder? Add it to TARGETS.
set -eu

TARGETS=".claude/skills .cursor/skills"
SOURCE=".agents/skills"

cd "$(dirname "$0")/.."

generate() {
  out_root=$1
  for skill_dir in "$SOURCE"/*/; do
    name=$(basename "$skill_dir")
    src="$SOURCE/$name/SKILL.md"
    [ -f "$src" ] || continue
    description=$(sed -n 's/^description: //p' "$src" | head -n 1)
    mkdir -p "$out_root/$name"
    cat > "$out_root/$name/SKILL.md" <<EOF
---
name: $name
description: $description
---

<!-- Generated by scripts/sync-agent-skills.sh — edit $src instead. -->

Read \`$src\` (from the repository root) and follow it exactly.
EOF
  done
}

if [ "${1:-}" = "--check" ]; then
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  generate "$tmp/expected"
  status=0
  for target in $TARGETS; do
    if ! diff -r "$tmp/expected" "$target" >/dev/null 2>&1; then
      echo "out of date: $target — run: sh scripts/sync-agent-skills.sh" >&2
      status=1
    fi
  done
  [ $status -eq 0 ] && echo "agent skills in sync"
  exit $status
fi

for target in $TARGETS; do
  rm -rf "$target"
  generate "$target"
  echo "synced $target"
done
